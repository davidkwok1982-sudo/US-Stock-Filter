def _key(value: str | None) -> str:
    return " ".join((value or "").replace("—", "-").split()).casefold()


def translate(table: dict[str, str], value: str | None) -> str | None:
    text = " ".join((value or "").split())
    if not text:
        return None
    return table.get(_key(text), text)


def sector_zh(value: str | None) -> str | None:
    return translate(SECTORS, value)


def industry_zh(value: str | None) -> str | None:
    return translate(INDUSTRIES, value)


def group_labels(groups: list[str]) -> list[str]:
    order = ["sp500", "ndx", "sp400"]
    return [GROUP_LABELS[g] for g in order if g in groups]
